#!/usr/bin/env python3
"""
gen_dispatch.py - build the seg:off -> lifted-function table.

The new lifter (pcrecomp lift16) emits recomp_dispatch(cpu, seg, off) for
indirect and unresolved far call/jmp. Every such target that we lifted has a
name of the form far_SSSS_OOOO, where SSSS:OOOO is the *image* segment:offset
(the same space the EXEPACK dump is in). Scan the generated C for those
definitions and emit a sorted table keyed by image linear address.

    py -3 tools/recomp/gen_dispatch.py RecompiledFuncs
"""
import re, sys, glob, os

DEF = re.compile(r'^void\s+(far_([0-9A-F]{4})_([0-9A-F]{4}))\s*\(CPU\s*\*\s*cpu\)\s*(?:\{|$)', re.M)

def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else 'RecompiledFuncs'
    seen = {}
    for path in sorted(glob.glob(os.path.join(outdir, '*.c'))):
        if os.path.basename(path) == 'civ_dispatch.c':
            continue
        src = open(path, encoding='utf-8', errors='replace').read()
        for name, seg, off in DEF.findall(src):
            seen.setdefault((int(seg, 16) * 16 + int(off, 16)), name)

    rows = sorted(seen.items())
    out = os.path.join(outdir, 'civ_dispatch.c')
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* civ_dispatch.c - AUTO-GENERATED by tools/recomp/gen_dispatch.py */\n')
        f.write('#include "recomp/cpu.h"\n\n')
        f.write('typedef struct { unsigned long addr; void (*fn)(CPU*); } civ_dispatch_entry;\n\n')
        for _, name in rows:
            f.write(f'extern void {name}(CPU *cpu);\n')
        f.write(f'\nconst civ_dispatch_entry g_dispatch[] = {{\n')
        for addr, name in rows:
            f.write(f'    {{ 0x{addr:06X}UL, {name} }},\n')
        f.write('};\nconst int g_dispatch_count = %d;\n' % len(rows))
    print(f'{out}: {len(rows)} entries')

if __name__ == '__main__':
    main()
